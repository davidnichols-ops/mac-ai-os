"""Trajectory recorder — training-quality telemetry for every agent interaction.

Every completed task produces a structured trajectory that can become a future
Adaptive Operator training example. The trajectory captures:

    User intent
      → Model decision
        → Tool selected
          → Arguments
            → Environment result
              → Model interpretation
                → Next action
                  → Final outcome

This is the atomic unit of training data. The schema is designed to be
model-agnostic and environment-agnostic — any future model can learn from
trajectories generated by any previous model.

Schema versioning: bump SCHEMA_VERSION for breaking changes. The version
field is mandatory on every trajectory.
"""

from __future__ import annotations

import json
import time
import uuid
from dataclasses import dataclass, field
from datetime import UTC, datetime
from enum import StrEnum
from pathlib import Path
from typing import Any

from app.log import get_logger

log = get_logger(__name__)

SCHEMA_VERSION = "2.1.0"


class StepType(StrEnum):
    """What kind of step this is in the trajectory."""
    OBSERVATION = "observation"
    MODEL_OUTPUT = "model_output"
    TOOL_CALL = "tool_call"
    TOOL_RESULT = "tool_result"
    ERROR = "error"
    VERIFICATION = "verification"
    RECOVERY = "recovery"
    TERMINATION = "termination"


class ComputeMode(StrEnum):
    """Adaptive compute mode — how much reasoning the model allocated.

    Extended from local-operator's schema to support the full
    FAST/THINK/RECOVER/VERIFY lifecycle.
    """
    FAST = "fast"          # immediate action, minimal reasoning
    THINK = "think"        # extended reasoning before action
    RECOVER = "recover"    # reassess after failed hypothesis
    VERIFY = "verify"      # checking completed work


class FailureCategory(StrEnum):
    """Taxonomy of why a trajectory failed."""
    NONE = "none"
    WRONG_TOOL = "wrong_tool"
    WRONG_ARGS = "wrong_args"
    WRONG_HYPOTHESIS = "wrong_hypothesis"
    MISSED_EVIDENCE = "missed_evidence"
    INCOMPLETE = "incomplete"
    PREMATURE_COMPLETION = "premature"
    INFINITE_LOOP = "infinite_loop"
    STEP_BUDGET_EXCEEDED = "step_budget"
    NONPROGRESSIVE = "nonprogressive"
    OVERTHINKING = "overthinking"
    UNDERTHINKING = "underthinking"
    SAFETY_VIOLATION = "safety"
    ENVIRONMENT_ERROR = "env_error"
    SYNTAX_ERROR = "syntax_error"
    MODEL_ERROR = "model_error"


class TrajectoryClass(StrEnum):
    """Quality classification for filtering training data."""
    A_GOLD = "A"                # correct and efficient
    B_CORRECT_INEFFICIENT = "B"  # correct but took unnecessary steps
    C_FAILED_EDUCATIONAL = "C"  # failed but valuable for recovery training
    D_INCORRECT = "D"           # incorrect, normally discard
    E_UNSAFE = "E"              # unsafe, always discard
    F_AMBIGUOUS = "F"           # hold out for manual review


@dataclass
class Step:
    """A single step in a trajectory."""
    step_id: int = 0
    step_type: StepType = StepType.MODEL_OUTPUT
    content: str = ""
    tool_name: str | None = None
    tool_args: dict[str, Any] = field(default_factory=dict)
    tool_result: Any | None = None
    tool_ok: bool | None = None
    error: str | None = None
    compute_mode: str | None = None  # "fast" | "think"
    timestamp: str = field(default_factory=lambda: datetime.now(UTC).isoformat())
    # Inference metrics
    generation_time_s: float = 0.0
    prompt_tokens: int = 0
    completion_tokens: int = 0
    tokens_per_second: float = 0.0
    # Safety
    risk_level: str | None = None
    approved: bool | None = None
    # Metadata
    metadata: dict[str, Any] = field(default_factory=dict)


@dataclass
class Trajectory:
    """A complete trajectory — one model attempting one task.

    This is the atomic unit of training data. Every agent loop execution
    produces exactly one trajectory. The trajectory is serializable to JSON
    for storage, replay, and future fine-tuning.

    Schema v2.1 adds: project, initial_state, model_decision, errors,
    recovery_actions, verification, quality_score.
    """
    trajectory_id: str = field(default_factory=lambda: f"traj_{uuid.uuid4().hex[:12]}")
    schema_version: str = SCHEMA_VERSION

    # Task
    task: str = ""  # the user's goal/intent
    project: str = ""  # project/workspace name (v2.1)
    task_context: str = ""  # injected context (workspace, session, etc.)
    initial_state: dict[str, Any] = field(default_factory=dict)  # v2.1: environment snapshot

    # Actor
    model_name: str = ""
    model_provider: str = ""

    # Model decision metadata (v2.1)
    model_decision: dict[str, Any] = field(default_factory=dict)
    # Expected: {"mode": "FAST|THINK|RECOVER|VERIFY", "confidence": 0.0-1.0}

    # Steps
    steps: list[Step] = field(default_factory=list)

    # Outcome
    success: bool = False
    failure_category: FailureCategory = FailureCategory.NONE
    failure_detail: str = ""
    final_answer: str = ""

    # Errors and recovery (v2.1)
    errors: list[dict[str, Any]] = field(default_factory=list)
    recovery_actions: list[dict[str, Any]] = field(default_factory=list)

    # Verification (v2.1)
    verification: dict[str, Any] = field(default_factory=dict)
    # Expected: {"verified": bool, "method": str, "detail": str}

    # Quality (v2.1 — filled by external classifier)
    quality_score: float = 0.0  # 0.0-1.0, assigned by quality classifier

    # Classification (filled by external classifier)
    trajectory_class: TrajectoryClass | None = None

    # Metrics
    total_steps: int = 0
    total_tool_calls: int = 0
    total_tokens: int = 0
    total_generation_time_s: float = 0.0
    time_to_completion_s: float = 0.0

    # Adaptive compute metrics
    fast_steps: int = 0
    think_steps: int = 0
    recover_steps: int = 0  # v2.1
    verify_steps: int = 0  # v2.1
    compute_mode_switches: int = 0

    # Safety
    safety_violations: int = 0
    approvals_requested: int = 0

    # Timestamps
    created_at: str = field(default_factory=lambda: datetime.now(UTC).isoformat())
    completed_at: str | None = None

    # Reproducibility
    config: dict[str, Any] = field(default_factory=dict)

    def add_step(self, step: Step) -> None:
        step.step_id = len(self.steps)
        self.steps.append(step)
        self.total_steps = len(self.steps)

    def finalize(self, *, success: bool, final_answer: str = "") -> None:
        """Set computed fields after trajectory is complete."""
        self.success = success
        self.final_answer = final_answer
        self.total_steps = len(self.steps)
        self.total_tool_calls = sum(1 for s in self.steps if s.step_type == StepType.TOOL_CALL)
        self.total_tokens = sum(s.completion_tokens for s in self.steps)
        self.total_generation_time_s = sum(s.generation_time_s for s in self.steps)

        # Compute adaptive metrics
        prev_mode: str | None = None
        for s in self.steps:
            if s.compute_mode is None:
                continue
            if s.compute_mode == ComputeMode.FAST.value:
                self.fast_steps += 1
            elif s.compute_mode == ComputeMode.THINK.value:
                self.think_steps += 1
            elif s.compute_mode == ComputeMode.RECOVER.value:
                self.recover_steps += 1
            elif s.compute_mode == ComputeMode.VERIFY.value:
                self.verify_steps += 1
            if prev_mode is not None and s.compute_mode != prev_mode:
                self.compute_mode_switches += 1
            prev_mode = s.compute_mode

        # Collect errors and recovery actions from steps (v2.1)
        for s in self.steps:
            if s.step_type == StepType.ERROR and s.error:
                self.errors.append({
                    "step_id": s.step_id,
                    "error": s.error,
                    "timestamp": s.timestamp,
                })
            if s.step_type == StepType.RECOVERY:
                self.recovery_actions.append({
                    "step_id": s.step_id,
                    "content": s.content,
                    "timestamp": s.timestamp,
                })

        if self.completed_at is None:
            self.completed_at = datetime.now(UTC).isoformat()

    def to_dict(self) -> dict[str, Any]:
        """Serialize to a JSON-compatible dict."""
        return {
            "trajectory_id": self.trajectory_id,
            "schema_version": self.schema_version,
            "task": self.task,
            "project": self.project,
            "task_context": self.task_context,
            "initial_state": self.initial_state,
            "model_name": self.model_name,
            "model_provider": self.model_provider,
            "model_decision": self.model_decision,
            "steps": [
                {
                    "step_id": s.step_id,
                    "step_type": s.step_type.value,
                    "content": s.content[:5000],  # truncate for storage
                    "tool_name": s.tool_name,
                    "tool_args": s.tool_args,
                    "tool_result": str(s.tool_result)[:5000] if s.tool_result is not None else None,
                    "tool_ok": s.tool_ok,
                    "error": s.error,
                    "compute_mode": s.compute_mode,
                    "timestamp": s.timestamp,
                    "generation_time_s": s.generation_time_s,
                    "prompt_tokens": s.prompt_tokens,
                    "completion_tokens": s.completion_tokens,
                    "tokens_per_second": s.tokens_per_second,
                    "risk_level": s.risk_level,
                    "approved": s.approved,
                    "metadata": s.metadata,
                }
                for s in self.steps
            ],
            "success": self.success,
            "failure_category": self.failure_category.value,
            "failure_detail": self.failure_detail,
            "final_answer": self.final_answer[:5000],
            "errors": self.errors,
            "recovery_actions": self.recovery_actions,
            "verification": self.verification,
            "quality_score": self.quality_score,
            "trajectory_class": self.trajectory_class.value if self.trajectory_class else None,
            "total_steps": self.total_steps,
            "total_tool_calls": self.total_tool_calls,
            "total_tokens": self.total_tokens,
            "total_generation_time_s": self.total_generation_time_s,
            "time_to_completion_s": self.time_to_completion_s,
            "fast_steps": self.fast_steps,
            "think_steps": self.think_steps,
            "recover_steps": self.recover_steps,
            "verify_steps": self.verify_steps,
            "compute_mode_switches": self.compute_mode_switches,
            "safety_violations": self.safety_violations,
            "approvals_requested": self.approvals_requested,
            "created_at": self.created_at,
            "completed_at": self.completed_at,
            "config": self.config,
        }

    def to_json(self, *, indent: int = 2) -> str:
        return json.dumps(self.to_dict(), indent=indent, default=str)

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> Trajectory:
        """Deserialize a trajectory from a dict (e.g. loaded from JSON).

        Handles both v2.0 and v2.1 schemas. Missing v2.1 fields default
        to empty values.
        """
        traj = cls(
            trajectory_id=data.get("trajectory_id", ""),
            schema_version=data.get("schema_version", "2.0.0"),
            task=data.get("task", ""),
            project=data.get("project", ""),
            task_context=data.get("task_context", ""),
            initial_state=data.get("initial_state", {}),
            model_name=data.get("model_name", ""),
            model_provider=data.get("model_provider", ""),
            model_decision=data.get("model_decision", {}),
            success=data.get("success", False),
            failure_category=FailureCategory(data.get("failure_category", "none")),
            failure_detail=data.get("failure_detail", ""),
            final_answer=data.get("final_answer", ""),
            errors=data.get("errors", []),
            recovery_actions=data.get("recovery_actions", []),
            verification=data.get("verification", {}),
            quality_score=data.get("quality_score", 0.0),
            total_steps=data.get("total_steps", 0),
            total_tool_calls=data.get("total_tool_calls", 0),
            total_tokens=data.get("total_tokens", 0),
            total_generation_time_s=data.get("total_generation_time_s", 0.0),
            time_to_completion_s=data.get("time_to_completion_s", 0.0),
            fast_steps=data.get("fast_steps", 0),
            think_steps=data.get("think_steps", 0),
            recover_steps=data.get("recover_steps", 0),
            verify_steps=data.get("verify_steps", 0),
            compute_mode_switches=data.get("compute_mode_switches", 0),
            safety_violations=data.get("safety_violations", 0),
            approvals_requested=data.get("approvals_requested", 0),
            created_at=data.get("created_at", ""),
            completed_at=data.get("completed_at"),
            config=data.get("config", {}),
        )
        # Reconstruct steps
        for s_data in data.get("steps", []):
            step = Step(
                step_id=s_data.get("step_id", 0),
                step_type=StepType(s_data.get("step_type", "model_output")),
                content=s_data.get("content", ""),
                tool_name=s_data.get("tool_name"),
                tool_args=s_data.get("tool_args", {}),
                tool_result=s_data.get("tool_result"),
                tool_ok=s_data.get("tool_ok"),
                error=s_data.get("error"),
                compute_mode=s_data.get("compute_mode"),
                timestamp=s_data.get("timestamp", ""),
                generation_time_s=s_data.get("generation_time_s", 0.0),
                prompt_tokens=s_data.get("prompt_tokens", 0),
                completion_tokens=s_data.get("completion_tokens", 0),
                tokens_per_second=s_data.get("tokens_per_second", 0.0),
                risk_level=s_data.get("risk_level"),
                approved=s_data.get("approved"),
                metadata=s_data.get("metadata", {}),
            )
            traj.steps.append(step)
        # Restore trajectory class if present
        tc = data.get("trajectory_class")
        if tc:
            traj.trajectory_class = TrajectoryClass(tc)
        return traj


class TrajectoryRecorder:
    """Records a trajectory during agent loop execution.

    Wraps the Trajectory dataclass with convenience methods for recording
    each type of step. Also persists to disk and/or SQLite.
    """

    def __init__(
        self,
        *,
        task: str = "",
        model_name: str = "",
        model_provider: str = "",
        task_context: str = "",
        project: str = "",
        initial_state: dict[str, Any] | None = None,
        persist_dir: Path | None = None,
    ):
        self.trajectory = Trajectory(
            task=task,
            model_name=model_name,
            model_provider=model_provider,
            task_context=task_context,
            project=project,
            initial_state=initial_state or {},
        )
        self._persist_dir = persist_dir
        self._start_time = time.monotonic()

    def record_model_output(
        self,
        content: str,
        *,
        compute_mode: str | None = None,
        generation_time_s: float = 0.0,
        prompt_tokens: int = 0,
        completion_tokens: int = 0,
        tokens_per_second: float = 0.0,
    ) -> Step:
        step = Step(
            step_type=StepType.MODEL_OUTPUT,
            content=content,
            compute_mode=compute_mode,
            generation_time_s=generation_time_s,
            prompt_tokens=prompt_tokens,
            completion_tokens=completion_tokens,
            tokens_per_second=tokens_per_second,
        )
        self.trajectory.add_step(step)
        return step

    def record_tool_call(
        self,
        tool_name: str,
        args: dict[str, Any],
        *,
        risk_level: str | None = None,
    ) -> Step:
        step = Step(
            step_type=StepType.TOOL_CALL,
            tool_name=tool_name,
            tool_args=args,
            risk_level=risk_level,
        )
        self.trajectory.add_step(step)
        return step

    def record_tool_result(
        self,
        result: Any,
        *,
        ok: bool = True,
        error: str | None = None,
        approved: bool | None = None,
    ) -> Step:
        step = Step(
            step_type=StepType.TOOL_RESULT,
            tool_result=result,
            tool_ok=ok,
            error=error,
            approved=approved,
        )
        self.trajectory.add_step(step)
        return step

    def record_error(self, error: str) -> Step:
        step = Step(step_type=StepType.ERROR, error=error)
        self.trajectory.add_step(step)
        return step

    def record_recovery(self, content: str, *, compute_mode: str | None = None) -> Step:
        """Record a recovery action — model changing approach after failure."""
        step = Step(
            step_type=StepType.RECOVERY,
            content=content,
            compute_mode=compute_mode or ComputeMode.RECOVER.value,
        )
        self.trajectory.add_step(step)
        return step

    def record_verification(self, passed: bool, detail: str = "") -> Step:
        step = Step(
            step_type=StepType.VERIFICATION,
            content=detail,
            metadata={"passed": passed},
        )
        self.trajectory.add_step(step)
        return step

    def record_termination(self, success: bool, detail: str = "") -> Step:
        step = Step(
            step_type=StepType.TERMINATION,
            content=detail,
            metadata={"success": success},
        )
        self.trajectory.add_step(step)
        return step

    def finalize(self, *, success: bool, final_answer: str = "") -> Trajectory:
        self.trajectory.time_to_completion_s = time.monotonic() - self._start_time
        self.trajectory.finalize(success=success, final_answer=final_answer)
        if self._persist_dir:
            self._persist()
        return self.trajectory

    def _persist(self) -> None:
        """Save trajectory to disk as JSON."""
        if self._persist_dir is None:
            return
        self._persist_dir.mkdir(parents=True, exist_ok=True)
        path = self._persist_dir / f"{self.trajectory.trajectory_id}.json"
        try:
            path.write_text(self.trajectory.to_json())
            log.info("trajectory.persisted", path=str(path), steps=self.trajectory.total_steps)
        except Exception as e:
            log.warning("trajectory.persist.failed", path=str(path), error=str(e))
